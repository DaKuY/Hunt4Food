import {
  hasAppGrant,
  parseSessionPayload,
  readCookie,
  SESSION_COOKIE,
  verifySessionToken,
  type SessionPayload,
} from './token.js'

export type LodgeLookup = 'unauthorized' | 'unavailable' | SessionPayload

export type AuthorizeDeps = {
  fetchLodge?: (token: string) => Promise<LodgeLookup>
}

export type GateDecision =
  | { type: 'allow'; session: SessionPayload }
  | { type: 'login' }
  | { type: 'unavailable' }

export { hasAppGrant }

export function sessionFromUnknown(data: unknown): SessionPayload | null {
  if (!data || typeof data !== 'object') return null
  const record = data as Record<string, unknown>
  if (record.authenticated === false) return null
  if ('user' in record) {
    if (!record.user || typeof record.user !== 'object') return null
    return parseSessionPayload(record.user as Record<string, unknown>)
  }
  const nested = record.session ?? record
  if (!nested || typeof nested !== 'object') return null
  return parseSessionPayload(nested as Record<string, unknown>)
}

export async function fetchLodgeSession(
  lodgeOrigin: string,
  token: string,
  fetchImpl: typeof fetch = fetch,
): Promise<LodgeLookup> {
  try {
    const res = await fetchImpl(`${lodgeOrigin}/api/session`, {
      method: 'GET',
      headers: {
        accept: 'application/json',
        cookie: `${SESSION_COOKIE}=${token}`,
      },
      redirect: 'manual',
      signal: AbortSignal.timeout(2500),
    })
    if (res.status === 401 || res.status === 403) return 'unauthorized'
    if (!res.ok) return 'unavailable'
    const data: unknown = await res.json()
    if (data && typeof data === 'object' && (data as { user?: unknown }).user === null) {
      return 'unauthorized'
    }
    if (data && typeof data === 'object' && (data as { authenticated?: unknown }).authenticated === false) {
      return 'unauthorized'
    }
    const session = sessionFromUnknown(data)
    if (!session) return 'unavailable'
    return session
  } catch {
    return 'unavailable'
  }
}


 // Cache confirmed lodge answers for the short burst of HTML/API requests
 // generated by one launch. Never cache logout or outage results.
 const LODGE_CACHE_TTL_MS = 15_000;
 const LODGE_CACHE_MAX = 500;
 const lodgeAnswers = new Map<string, { answer: LodgeLookup; expires: number }>();
 const lodgePending = new Map<string, Promise<LodgeLookup>>();

 async function cachedLodgeSession(lodgeOrigin: string, token: string): Promise<LodgeLookup> {
   const key = `${lodgeOrigin}|${token}`;
   const hit = lodgeAnswers.get(key);
   if (hit && hit.expires > Date.now()) return hit.answer;
   if (hit) lodgeAnswers.delete(key);
   const pending = lodgePending.get(key);
   if (pending) return pending;
   const request = fetchLodgeSession(lodgeOrigin, token).then((answer) => {
     if (answer !== 'unauthorized' && answer !== 'unavailable') {
       if (lodgeAnswers.size >= LODGE_CACHE_MAX) lodgeAnswers.delete(lodgeAnswers.keys().next().value!);
       lodgeAnswers.set(key, { answer, expires: Date.now() + LODGE_CACHE_TTL_MS });
     }
     return answer;
   }).finally(() => lodgePending.delete(key));
   lodgePending.set(key, request);
   return request;
 }

export async function authorizeRequest(
  cookieHeader: string | null | undefined,
  authSecret: string,
  lodgeOrigin: string,
  deps: AuthorizeDeps = {},
): Promise<GateDecision> {
  const token = readCookie(cookieHeader, SESSION_COOKIE)
  if (!token) return { type: 'login' }

  const lodge = await (deps.fetchLodge ?? ((t) => cachedLodgeSession(lodgeOrigin, t)))(token)

  if (lodge === 'unauthorized') return { type: 'login' }
  if (lodge !== 'unavailable') {
    // Base Camp is authoritative for live sessions and current grants.
    return { type: 'allow', session: lodge }
  }

  // Optional compatibility fallback for older deployments. New product
  // projects do not need AUTH_SECRET; when it is absent, fail closed cleanly.
  if (!authSecret) return { type: 'unavailable' }
  const jwtSession = await verifySessionToken(token, authSecret)
  return jwtSession ? { type: 'allow', session: jwtSession } : { type: 'unavailable' }
}

export function requestWantsJson(request: Request): boolean {
  const path = new URL(request.url).pathname
  if (path === '/api' || path.startsWith('/api/')) return true
  const xhr = request.headers.get('x-requested-with')
  if (xhr && xhr.toLowerCase() === 'xmlhttprequest') return true
  const accept = request.headers.get('accept') ?? ''
  return accept.includes('application/json') && !accept.includes('text/html')
}

export function publicOriginFrom(request: Request): string {
  const url = new URL(request.url)
  const forwardedHost = request.headers.get('x-forwarded-host')
  const host = forwardedHost ?? request.headers.get('host') ?? url.host
  const proto = request.headers.get('x-forwarded-proto') ?? url.protocol.replace(':', '')
  return `${proto}://${host}`
}
